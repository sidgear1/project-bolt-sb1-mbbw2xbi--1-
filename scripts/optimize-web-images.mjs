import { spawn } from "node:child_process";
import { copyFile, mkdir, readdir, stat, writeFile } from "node:fs/promises";
import path from "node:path";

const projectRoot = process.cwd();
const publicRoot = path.join(projectRoot, "public");
const manifestPath = path.join(projectRoot, "src", "generated", "optimizedImagePaths.ts");
const mediaManifestPath = path.join(projectRoot, "src", "generated", "preloadMediaPaths.ts");
const externalRoot = "C:\\Users\\david\\Desktop\\ai world map\\web-optimized";
const concurrency = 4;

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(entries.map(async (entry) => {
    const fullPath = path.join(directory, entry.name);
    return entry.isDirectory() ? walk(fullPath) : [fullPath];
  }));
  return nested.flat();
}

function runFfmpeg(source, destination) {
  return new Promise((resolve, reject) => {
    const child = spawn("ffmpeg", [
      "-y", "-hide_banner", "-loglevel", "error",
      "-i", source,
      "-frames:v", "1",
      "-map_metadata", "-1",
      "-c:v", "libwebp",
      "-quality", "88",
      "-compression_level", "5",
      destination,
    ], { windowsHide: true });
    let error = "";
    child.stderr.on("data", chunk => { error += chunk; });
    child.on("error", reject);
    child.on("close", code => code === 0 ? resolve() : reject(new Error(error || `ffmpeg exited with ${code}`)));
  });
}

const pngFiles = (await walk(publicRoot))
  .filter(file => file.toLowerCase().endsWith(".png"));

let cursor = 0;
let converted = 0;
let skipped = 0;
const failures = [];

async function worker() {
  while (cursor < pngFiles.length) {
    const source = pngFiles[cursor++];
    const destination = source.replace(/\.png$/i, ".webp");
    const relativeSource = path.relative(publicRoot, source);
    try {
      const [sourceInfo, destinationInfo] = await Promise.all([
        stat(source),
        stat(destination).catch(() => null),
      ]);
      if (!destinationInfo || destinationInfo.mtimeMs < sourceInfo.mtimeMs) {
        await runFfmpeg(source, destination);
        converted += 1;
      } else {
        skipped += 1;
      }

      const externalDestination = path.join(externalRoot, relativeSource.replace(/\.png$/i, ".webp"));
      await mkdir(path.dirname(externalDestination), { recursive: true });
      await copyFile(destination, externalDestination);
    } catch (error) {
      failures.push(`${relativeSource}: ${error instanceof Error ? error.message : String(error)}`);
    }
  }
}

await Promise.all(Array.from({ length: concurrency }, worker));

const availableSources = [];
for (const source of pngFiles) {
  const destination = source.replace(/\.png$/i, ".webp");
  try {
    await stat(destination);
    availableSources.push(path.relative(publicRoot, source).split(path.sep).join("/"));
  } catch {
    // Keep the original PNG URL when conversion was unavailable.
  }
}

await mkdir(path.dirname(manifestPath), { recursive: true });
await writeFile(
  manifestPath,
  `// Generated by scripts/optimize-web-images.mjs. PNG originals remain as fallbacks.\nexport const OPTIMIZED_IMAGE_PATHS = new Set<string>(${JSON.stringify(availableSources.sort(), null, 2)});\n`,
  "utf8",
);

const allPublicFiles = await walk(publicRoot);
const preloadMedia = allPublicFiles
  .map(file => path.relative(publicRoot, file).split(path.sep).join("/"))
  .filter(relative =>
    (/^(?:audio|music)\/.+\.(?:mp3|m4a)$/i.test(relative)) ||
    [
      "scenes/masked-man/source/3 roam/a23 music.mp3",
      "scenes/masked-man/source/a16 msuic Broken Staircase (Quiet Subtle Version) (1).mp3",
      "scenes/masked-man/source/2 battle/a8 batle music .mp3",
      "videos/woodstock-roam-web.mp4",
      "scenes/masked-man/source/1 intro/masked-man-web.mp4",
    ].includes(relative)
  )
  .sort();

await writeFile(
  mediaManifestPath,
  `// Generated by scripts/optimize-web-images.mjs.\nexport const PRELOAD_MEDIA_PATHS = ${JSON.stringify(preloadMedia, null, 2)} as const;\n`,
  "utf8",
);

console.log(`Optimized images: ${converted} converted, ${skipped} already current, ${failures.length} failed.`);
if (failures.length) {
  console.error(failures.join("\n"));
  process.exitCode = 1;
}
